/**
 * The station: every phone in the network that runs WIFIGram.
 *
 * The green button calls, the blue button opens the chat.
 */
@Composable
fun StationScreen(
    engine: Intercom,
    onCall: (String) -> Unit,
    onChat: (String) -> Unit
) {
    val peers by engine.peers.collectAsStateWithLifecycle()

    if (peers.isEmpty()) {
        Box(
            modifier = Modifier.fillMaxSize(),
            contentAlignment = Alignment.Center
        ) {
            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                Icon(
                    Icons.Filled.Refresh,
                    contentDescription = null,
                    modifier = Modifier.size(56.dp),
                    tint = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Spacer(modifier = Modifier.height(12.dp))
                Text(
                    text = "Немає інших телефонів",
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Spacer(modifier = Modifier.height(6.dp))
                Text(
                    text = "Запустіть WIFIGram на іншому телефоні в цій мережі",
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    modifier = Modifier.padding(horizontal = 32.dp)
                )
            }
        }
        return
    }

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(bottom = 16.dp)
    ) {
        item {
            Text(
                text = "Станція: ${peers.count { it.online }} телефонів у мережі",
                style = MaterialTheme.typography.labelMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(start = 20.dp, top = 8.dp, bottom = 4.dp)
            )
        }
        items(peers, key = { it.id }) { peer ->
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clickable { onCall(peer.id) }
                    .padding(start = 16.dp, end = 8.dp, top = 8.dp, bottom = 8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Box {
                    Avatar(name = peer.name, size = 48)
                    Box(
                        modifier = Modifier
                            .align(Alignment.BottomEnd)
                            .size(14.dp)
                            .clip(CircleShape)
                            .background(MaterialTheme.colorScheme.surface)
                            .padding(2.dp)
                    ) {
                        StatusDot(peer.status, peer.online)
                    }
                }
                Spacer(modifier = Modifier.width(14.dp))
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = peer.name,
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.SemiBold,
                        color = MaterialTheme.colorScheme.onSurface,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                    Text(
                        text = statusText(peer),
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
                IconButton(onClick = { onChat(peer.id) }) {
                    Icon(
                        Icons.Filled.Chat,
                        contentDescription = "Чат",
                        tint = MaterialTheme.colorScheme.primary
                    )
                }
                IconButton(onClick = { onCall(peer.id) }) {
                    Icon(
                        Icons.Filled.Call,
                        contentDescription = "Дзвінок",
                        tint = CallGreen
                    )
                }
            }
        }
    }
}
